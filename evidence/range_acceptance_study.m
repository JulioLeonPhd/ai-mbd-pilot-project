function peaks = findLocalPeaks(power, valid)
%FINDLOCALPEAKS Find strict local maxima, treating exact plateaus once.

peaks = zeros(numel(power), 1);
peakCount = 0;
index = 1;
while index <= numel(power)
    if ~valid(index)
        index = index + 1;
    else
        segmentStart = index;
        while index < numel(power) && valid(index + 1)
            index = index + 1;
        end
        segmentEnd = index;
        plateauStart = segmentStart;
        while plateauStart <= segmentEnd
            plateauEnd = plateauStart;
            while plateauEnd < segmentEnd && ...
                    power(plateauEnd + 1) == power(plateauStart)
                plateauEnd = plateauEnd + 1;
            end
            hasTwoNeighbors = plateauStart > segmentStart && plateauEnd < segmentEnd;
            if hasTwoNeighbors && power(plateauStart - 1) < power(plateauStart) && ...
                    power(plateauEnd + 1) < power(plateauEnd)
                peakCount = peakCount + 1;
                peaks(peakCount) = floor((plateauStart + plateauEnd)/2);
            end
            plateauStart = plateauEnd + 1;
        end
        index = segmentEnd + 1;
    end
end
peaks = peaks(1:peakCount);
end

function selected = choosePeak(power, valid, ranges, truthRange, binWidth)
%CHOOSEPEAK Select the strongest eligible maximum with fixed tie-breaks.

selected = NaN;
peaks = findLocalPeaks(power, valid);
if isempty(peaks)
    return
end
eligible = peaks(abs(ranges(peaks) - truthRange) <= binWidth);
if isempty(eligible)
    return
end
peakPower = power(eligible);
bestPower = max(peakPower);
strongest = eligible(peakPower == bestPower);
distance = abs(ranges(strongest) - truthRange);
nearest = strongest(distance == min(distance));
selected = min(nearest);
end

function pair = evaluatePeakPair(magnitude, valid, ranges, nearRange, farRange, binWidth)
%EVALUATEPEAKPAIR Evaluate local peaks, distinctness, and valid intervening valley.

power = magnitude.^2;
nearIndex = choosePeak(power, valid, ranges, nearRange, binWidth);
farIndex = choosePeak(power, valid, ranges, farRange, binWidth);
pair = struct( ...
    "near_index", nearIndex, ...
    "far_index", farIndex, ...
    "near_found", isfinite(nearIndex), ...
    "far_found", isfinite(farIndex), ...
    "peaks_distinct", false, ...
    "valley_available", false, ...
    "valley_status", "unavailable_missing_peak", ...
    "valley_index", NaN, ...
    "valley_power", NaN, ...
    "valley_ratio", NaN, ...
    "valley_depth_db", NaN, ...
    "valley_depth_status", "unavailable", ...
    "valley_pass", false);
if ~(pair.near_found && pair.far_found)
    return
end
pair.peaks_distinct = nearIndex ~= farIndex;
if ~pair.peaks_distinct
    pair.valley_status = "unavailable_same_peak";
    return
end
leftIndex = min(nearIndex, farIndex);
rightIndex = max(nearIndex, farIndex);
if rightIndex <= leftIndex + 1
    pair.valley_status = "unavailable_no_intervening_bin";
    return
end
interior = leftIndex + 1:rightIndex - 1;
if ~all(valid(interior))
    pair.valley_status = "unavailable_invalid_intervening_bins";
    return
end
[minimumPower, valleyOffset] = min(power(interior));
weakerPeakPower = min(power(nearIndex), power(farIndex));
pair.valley_available = true;
pair.valley_status = "available";
pair.valley_index = interior(valleyOffset);
pair.valley_power = minimumPower;
pair.valley_ratio = minimumPower/weakerPeakPower;
if minimumPower == 0
    pair.valley_depth_db = NaN;
    pair.valley_depth_status = "negative_infinity_zero_valley_power";
else
    pair.valley_depth_db = 10*log10(pair.valley_ratio);
    pair.valley_depth_status = "finite";
end
pair.valley_pass = pair.valley_ratio <= 10^(-3/10);
end

function [width, leftCrossing, rightCrossing, status] = ...
        measureFwhm(magnitude, valid, ranges, peakIndex)
%MEASUREFWHM Interpolate nearest half-peak-power crossings within valid samples.

width = NaN;
leftCrossing = NaN;
rightCrossing = NaN;
status = "unavailable_peak_missing";
if ~isfinite(peakIndex)
    return
end
power = magnitude.^2;
halfPower = power(peakIndex)/2;
segmentStart = peakIndex;
while segmentStart > 1 && valid(segmentStart - 1)
    segmentStart = segmentStart - 1;
end
segmentEnd = peakIndex;
while segmentEnd < numel(valid) && valid(segmentEnd + 1)
    segmentEnd = segmentEnd + 1;
end
for index = peakIndex - 1:-1:segmentStart
    if power(index) <= halfPower && power(index + 1) >= halfPower
        if power(index + 1) == power(index)
            status = "unavailable_flat_left_half_power_crossing";
            return
        end
        leftCrossing = ranges(index) + (halfPower - power(index))* ...
            (ranges(index + 1) - ranges(index))/(power(index + 1) - power(index));
        break
    end
end
for index = peakIndex:segmentEnd - 1
    if power(index) >= halfPower && power(index + 1) <= halfPower
        if power(index + 1) == power(index)
            status = "unavailable_flat_right_half_power_crossing";
            return
        end
        rightCrossing = ranges(index) + (halfPower - power(index))* ...
            (ranges(index + 1) - ranges(index))/(power(index + 1) - power(index));
        break
    end
end
if isfinite(leftCrossing) && isfinite(rightCrossing)
    width = rightCrossing - leftCrossing;
    status = "available_sampled_response_diagnostic";
elseif ~isfinite(leftCrossing) && ~isfinite(rightCrossing)
    status = "unavailable_both_half_power_crossings_missing";
elseif ~isfinite(leftCrossing)
    status = "unavailable_left_half_power_crossing_missing";
else
    status = "unavailable_right_half_power_crossing_missing";
end
end

