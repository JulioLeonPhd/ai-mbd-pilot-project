function seedTable = makeSeedTable(baseSeed)
%MAKESEEDTABLE Freeze the path, stream, and purpose-specific seed mapping.

template = struct( ...
    "path_index", 0, ...
    "path", "", ...
    "stream_index_zero_based", 0, ...
    "record_index", 0, ...
    "purpose", "", ...
    "seed", 0);
seedTable = repmat(template, 32, 1);
index = 0;
for pathIndex = 0:1
    for streamIndex = 0:3
        for recordIndex = 0:3
            index = index + 1;
            seed = mod(double(baseSeed) + 1000*pathIndex + ...
                10*streamIndex + recordIndex, 2^32);
            if recordIndex == 0
                purpose = "noise_only";
            else
                purpose = "separation_seed_" + string(recordIndex);
            end
            seedTable(index) = struct( ...
                "path_index", pathIndex, ...
                "path", pathName(pathIndex), ...
                "stream_index_zero_based", streamIndex, ...
                "record_index", recordIndex, ...
                "purpose", purpose, ...
                "seed", seed);
        end
    end
end
end

function [noiseOnly, noiseBank, noiseQuant, noiseQuantStats, noiseRange, noisePower] = ...
        buildNoiseEvidence(design, constants, seedTable)
%BUILDNOISEEVIDENCE Generate one noise-only and three reused noise records.

noiseTemplate = struct( ...
    "path_index", 0, ...
    "path", "", ...
    "seed_record_index", 0, ...
    "receiver_input_noise_power_estimate_w", zeros(1, 4), ...
    "receiver_input_noise_counts_rms", zeros(1, 4), ...
    "range_input_noise_power_counts_squared", zeros(1, 4), ...
    "range_input_noise_interior_range_m", zeros(1, 2), ...
    "range_input_noise_interior_range_convention", ...
    "Valid range-input outputs with coordinate within the inclusive 20–70 km interval", ...
    "range_input_noise_interior_indices_zero_based_inclusive", zeros(1, 2), ...
    "range_input_noise_interior_sample_count", 0, ...
    "output_noise_power_counts_squared", zeros(1, 4), ...
    "roi_complete_valid_bins", 0, ...
    "quantizer_statistics", repmat(makeQuantTemplate(), 1, 4), ...
    "adc_clipping", false);
noiseOnly = repmat(noiseTemplate, 2, 1);
noiseBank = cell(2, 3);
noiseQuant = cell(2, 3);
noiseQuantStats = cell(2, 3);
noiseRange = cell(2, 3);
noisePower = zeros(2, 4);

for pathIndex = 0:1
    if pathIndex == 0
        inputCount = constants.baseband_sample_count;
        inputStart = constants.blank_baseband_samples + 1;
    else
        inputCount = constants.adc_sample_count;
        inputStart = constants.blank_adc_samples + 1;
    end
    noiseInput = zeros(inputCount, 4);
    for streamIndex = 0:3
        seedRow = findSeedRow(seedTable, pathIndex, streamIndex, 0);
        noiseInput(:, streamIndex + 1) = generateNoiseRecord( ...
            pathIndex, seedRow.seed, constants);
    end
    [noiseBaseband, noiseValid, rangeOrigin, metadata, quantStats] = ...
        preparePathInput(pathIndex, noiseInput, design, constants, pathIndex == 1);
    if pathIndex == 0
        for streamIndex = 1:4
            quantStats(streamIndex).status = "not_applicable_ideal_path";
        end
    end
    [noiseCompressed, compressedValid, rangeCenters] = compressRange( ...
        noiseBaseband, noiseValid, constants.reference, constants, rangeOrigin);
    roi = rangeCenters >= constants.output_noise_roi_m(1) & ...
        rangeCenters <= constants.output_noise_roi_m(2) & all(compressedValid, 2);
    assert(any(roi), "The stationary noise-only ROI must contain valid bins.");
    outputPower = mean(abs(noiseCompressed(roi, :)).^2, 1);
    noisePower(pathIndex + 1, :) = outputPower;
    if pathIndex == 0
        receiverInputNoisePower = mean(abs(noiseInput(inputStart:end, :)).^2, 1) ./ ...
            (2*constants.count_scale^2);
        receiverInputNoiseRms = sqrt(mean(abs(noiseInput(inputStart:end, :)).^2, 1));
    else
        receiverInputNoisePower = mean(noiseInput(inputStart:end, :).^2, 1) ./ ...
            constants.count_scale^2;
        receiverInputNoiseRms = sqrt(mean(noiseInput(inputStart:end, :).^2, 1));
    end
    rangeInputInterior = rangeCenters >= constants.output_noise_roi_m(1) & ...
        rangeCenters <= constants.output_noise_roi_m(2) & all(noiseValid, 2);
    assert(any(rangeInputInterior), ...
        "The valid range-input noise interior must contain samples.");
    rangeInputInteriorIndices = find(rangeInputInterior) - 1;
    rangeInputNoisePower = mean(abs(noiseBaseband(rangeInputInterior, :)).^2, 1);
    noiseOnly(pathIndex + 1) = struct( ...
        "path_index", pathIndex, ...
        "path", pathName(pathIndex), ...
        "seed_record_index", 0, ...
        "receiver_input_noise_power_estimate_w", receiverInputNoisePower, ...
        "receiver_input_noise_counts_rms", receiverInputNoiseRms, ...
        "range_input_noise_power_counts_squared", rangeInputNoisePower, ...
        "range_input_noise_interior_range_m", constants.output_noise_roi_m, ...
        "range_input_noise_interior_range_convention", ...
        "Valid range-input outputs with coordinate within the inclusive 20–70 km interval", ...
        "range_input_noise_interior_indices_zero_based_inclusive", ...
        [rangeInputInteriorIndices(1), rangeInputInteriorIndices(end)], ...
        "range_input_noise_interior_sample_count", numel(rangeInputInteriorIndices), ...
        "output_noise_power_counts_squared", outputPower, ...
        "roi_complete_valid_bins", sum(roi), ...
        "quantizer_statistics", quantStats, ...
        "adc_clipping", any([quantStats.rounded_out_of_range_count] > 0));
    if pathIndex == 1
        assert(metadata.groupDelayOutputSamples == 31, ...
            "Noise-only DDC metadata must retain the configured group delay.");
    end

    for seedIndex = 1:3
        noiseInput = zeros(inputCount, 4);
        for streamIndex = 0:3
            seedRow = findSeedRow(seedTable, pathIndex, streamIndex, seedIndex);
            noiseInput(:, streamIndex + 1) = generateNoiseRecord( ...
                pathIndex, seedRow.seed, constants);
        end
        noiseBank{pathIndex + 1, seedIndex} = noiseInput;
        if pathIndex == 1
            [noiseQuant{pathIndex + 1, seedIndex}, ...
                noiseQuantStats{pathIndex + 1, seedIndex}] = quantizeCounts(noiseInput);
        else
            noiseQuant{pathIndex + 1, seedIndex} = noiseInput;
            noiseQuantStats{pathIndex + 1, seedIndex} = ...
                repmat(makeQuantTemplate(), 1, 4);
            for streamIndex = 1:4
                noiseQuantStats{pathIndex + 1, seedIndex}(streamIndex).status = ...
                    "not_applicable_ideal_path";
            end
        end
        [rawNoiseBaseband, rawNoiseValid, rawOrigin] = preparePathInput( ...
            pathIndex, noiseInput, design, constants, false);
        [noiseRange{pathIndex + 1, seedIndex}, ~, ~] = compressRange( ...
            rawNoiseBaseband, rawNoiseValid, constants.reference, constants, rawOrigin);
    end
end
end

function row = findSeedRow(seedTable, pathIndex, streamIndex, recordIndex)
%FINDSEEDROW Locate the already-frozen seed for one noise realization.

matches = [seedTable.path_index] == pathIndex & ...
    [seedTable.stream_index_zero_based] == streamIndex & ...
    [seedTable.record_index] == recordIndex;
row = seedTable(find(matches, 1));
end

function counts = generateNoiseRecord(pathIndex, seed, constants)
%GENERATENOISERECORD Synthesize one crop from the prescribed periodic spectrum.

randomStream = RandStream("mt19937ar", "Seed", double(seed));
if pathIndex == 0
    fftLength = constants.ideal_fft_length;
    bins = (-5000:5000).';
    weights = ones(size(bins));
    weights([1, end]) = 0.5;
    realPart = randn(randomStream, numel(bins), 1);
    imagPart = randn(randomStream, numel(bins), 1);
    coefficients = sqrt(fftLength*constants.baseband_rate_hz* ...
        constants.noise_psd_w_per_hz*weights).*(realPart + 1i*imagPart);
    spectrum = complex(zeros(fftLength, 1));
    spectrum(mod(bins, fftLength) + 1) = coefficients;
    record = ifft(spectrum);
    counts = constants.count_scale*record(constants.ideal_crop);
    counts(1:constants.blank_baseband_samples) = 0;
else
    fftLength = constants.adc_fft_length;
    bins = (45000:55000).';
    weights = ones(size(bins));
    weights([1, end]) = 0.5;
    realPart = randn(randomStream, numel(bins), 1);
    imagPart = randn(randomStream, numel(bins), 1);
    coefficients = sqrt(fftLength*constants.adc_rate_hz* ...
        constants.noise_psd_w_per_hz*weights/4).*(realPart + 1i*imagPart);
    spectrum = complex(zeros(fftLength, 1));
    spectrum(bins + 1) = coefficients;
    spectrum(fftLength - bins + 1) = conj(coefficients);
    record = real(ifft(spectrum));
    counts = constants.count_scale*record(constants.adc_crop);
    counts(1:constants.blank_adc_samples) = 0;
end
end

function [unitResponses, evidence] = deriveCommonRcs(design, constants, noisePower)
%DERIVECOMMONRCS Bound one shared RCS from the least favorable response.

unitTemplate = struct( ...
    "candidate_lags", zeros(0, 1), ...
    "candidate_ranges_m", zeros(0, 1), ...
    "candidate_response", complex(zeros(0, 1)), ...
    "candidate_valid", false(0, 1), ...
    "response_status", "not_evaluated");
unitResponses = repmat(unitTemplate, 2, numel(constants.geometry), 2);
minimumResponse = NaN(2, 4);
limitingTemplate = struct( ...
    "path_index", 0, ...
    "stream_index_zero_based", 0, ...
    "geometry_index", 0, ...
    "offset_bins", NaN, ...
    "phase_deg", NaN, ...
    "target", "", ...
    "lag", NaN, ...
    "response_magnitude_counts_per_input_count", NaN);
limiting = repmat(limitingTemplate, 2, 4);
minimumResponse(:) = Inf;
validCandidateMissing = false(2, numel(constants.geometry), 2);

for pathIndex = 0:1
    for geometryIndex = 1:numel(constants.geometry)
        geometry = constants.geometry(geometryIndex);
        targetRanges = [geometry.near_range_m, geometry.far_range_m];
        phases = [0, geometry.phase_deg*pi/180];
        for targetIndex = 1:2
            envelope = generateTargetEnvelope( ...
                targetRanges(targetIndex), phases(targetIndex), pathIndex, constants);
            unitInput = makePathSignal(envelope, pathIndex, constants);
            [baseband, inputValid, rangeOrigin] = preparePathInput( ...
                pathIndex, unitInput, design, constants, false);
            ranges = rangeOrigin + (0:constants.baseband_sample_count - 1).' * ...
                constants.range_spacing_m;
            candidateLags = find(abs(ranges - targetRanges(targetIndex)) <= ...
                constants.range_spacing_m) - 1;
            [candidateResponse, candidateValid] = directAtLags( ...
                baseband, inputValid, candidateLags, constants);
            unitResponses(pathIndex + 1, geometryIndex, targetIndex) = struct( ...
                "candidate_lags", candidateLags, ...
                "candidate_ranges_m", ranges(candidateLags + 1), ...
                "candidate_response", candidateResponse, ...
                "candidate_valid", candidateValid, ...
                "response_status", "evaluated");
            for streamIndex = 1:4
                usable = candidateValid(:, 1);
                if ~any(usable)
                    validCandidateMissing(pathIndex + 1, geometryIndex, targetIndex) = true;
                    continue
                end
                magnitudes = abs(candidateResponse(usable, 1));
                [candidateMinimum, minimumIndex] = min(magnitudes);
                if candidateMinimum < minimumResponse(pathIndex + 1, streamIndex)
                    candidateLagsValid = candidateLags(usable);
                    minimumResponse(pathIndex + 1, streamIndex) = candidateMinimum;
                    limiting(pathIndex + 1, streamIndex) = struct( ...
                        "path_index", pathIndex, ...
                        "stream_index_zero_based", streamIndex - 1, ...
                        "geometry_index", geometryIndex, ...
                        "offset_bins", geometry.offset_bins, ...
                        "phase_deg", geometry.phase_deg, ...
                        "target", targetName(targetIndex), ...
                        "lag", candidateLagsValid(minimumIndex), ...
                        "response_magnitude_counts_per_input_count", candidateMinimum);
                end
            end
        end
    end
end

for pathIndex = 1:2
    if any(validCandidateMissing(pathIndex, :, :), "all")
        minimumResponse(pathIndex, :) = NaN;
    end
end
responseError = zeros(2, 4);
responseError(2, :) = norm(design.stage1Numerator, 1)* ...
    norm(design.stage2Numerator, 1);
farthestRange = max([constants.geometry.far_range_m]);
contributionTemplate = struct( ...
    "path_index", 0, ...
    "path", "", ...
    "stream_index_zero_based", 0, ...
    "noise_power_counts_squared", NaN, ...
    "noise_amplitude_at_30db_counts", NaN, ...
    "compressed_error_bound_counts", NaN, ...
    "least_favorable_response_counts_per_input_count", NaN, ...
    "response_ratio", NaN, ...
    "rcs_bound_m2", NaN, ...
    "limiting_response", limitingTemplate);
contributions = repmat(contributionTemplate, 8, 1);
index = 0;
for pathIndex = 0:1
    for streamIndex = 1:4
        index = index + 1;
        cValue = minimumResponse(pathIndex + 1, streamIndex);
        noiseValue = noisePower(pathIndex + 1, streamIndex);
        if cValue > 0 && isfinite(noiseValue)
            noiseAmplitude = sqrt(constants.thermal_noise_target_factor*noiseValue);
            ratio = (noiseAmplitude + responseError(pathIndex + 1, streamIndex))/cValue;
            bound = farthestRange^4/(2*constants.count_scale^2* ...
                constants.radar_constant)*ratio^2;
        else
            noiseAmplitude = NaN;
            ratio = NaN;
            bound = NaN;
        end
        contributions(index) = struct( ...
            "path_index", pathIndex, ...
            "path", pathName(pathIndex), ...
            "stream_index_zero_based", streamIndex - 1, ...
            "noise_power_counts_squared", noiseValue, ...
            "noise_amplitude_at_30db_counts", noiseAmplitude, ...
            "compressed_error_bound_counts", responseError(pathIndex + 1, streamIndex), ...
            "least_favorable_response_counts_per_input_count", cValue, ...
            "response_ratio", ratio, ...
            "rcs_bound_m2", bound, ...
            "limiting_response", limiting(pathIndex + 1, streamIndex));
    end
end
bounds = [contributions.rcs_bound_m2];
validBounds = isfinite(bounds);
if all(validBounds)
    [commonBound, limitingIndex] = max(bounds);
    limitingContribution = contributions(limitingIndex);
    commonRcs = constants.rcs_headroom*commonBound;
    derivationStatus = "derived";
else
    commonBound = NaN;
    commonRcs = NaN;
    limitingContribution = contributionTemplate;
    derivationStatus = "unavailable_zero_response_or_noise_estimate";
end

minimumStruct = struct( ...
    "ideal_counts_per_input_count", minimumResponse(1, :), ...
    "sampled_ddc_counts_per_input_count", minimumResponse(2, :), ...
    "limiting_response_by_path_stream", limiting);
evidence = struct( ...
    "status", derivationStatus, ...
    "radar_equation", ...
    "Pr=Kr*sigma/R^4; Kr=Pt*Gt*Gr*lambda^2/((4*pi)^3*L)", ...
    "tx_peak_power_w", constants.tx_power_w, ...
    "tx_gain_db", 23, ...
    "rx_gain_db_per_effective_elevation_row", 23, ...
    "lumped_signal_path_loss_db_applied_once", 6, ...
    "wavelength_m", constants.wavelength_m, ...
    "radar_constant", constants.radar_constant, ...
    "radar_constant_units", "W*m^4 per m^2 RCS", ...
    "farthest_tested_range_m", farthestRange, ...
    "noise_target_snr_linear", constants.thermal_noise_target_factor, ...
    "response_minima_counts_per_input_count", minimumStruct, ...
    "all_geometry_target_candidate_windows_valid", ~any(validCandidateMissing, "all"), ...
    "compressed_error_bound_counts_by_path", responseError, ...
    "sampled_error_bound_constituents", ...
    "2*(1/2-count error)*||h1||1*||h2||1*||s||1/M", ...
    "stage1_l1_norm", norm(design.stage1Numerator, 1), ...
    "stage2_l1_norm", norm(design.stage2Numerator, 1), ...
    "normalized_reference_l1_gain", 1, ...
    "contributions", contributions, ...
    "limiting_contribution", limitingContribution, ...
    "common_rcs_bound_m2", commonBound, ...
    "fixed_rcs_headroom_fraction", constants.rcs_headroom - 1, ...
    "common_rcs_m2", commonRcs, ...
    "derive_once_before_separation", true, ...
    "case_or_stream_normalization", false, ...
    "four_stream_signal_response_reused", true);
end

