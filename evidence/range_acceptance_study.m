%% Reference-only range acceptance numerical evidence study
% This study records numerical and physical evidence; it does not approve tolerances.
runRangeAcceptanceStudy(fileparts(mfilename("fullpath")));

function runRangeAcceptanceStudy(studyFolder)
%RUNRANGEACCEPTANCESTUDY Run the frozen range evidence matrix and write its report.

originalPath = path;
originalRng = rng;
stateCleanup = onCleanup(@() restoreStudyState(originalPath, originalRng));
sourceFolder = fullfile(fileparts(studyFolder), "src");
addpath(sourceFolder, "-begin");
reportPath = fullfile(studyFolder, "range_acceptance_results.json");
result = makeReportTemplate(reportPath);
runFailure = [];

try
    result = executeRangeStudy(studyFolder, sourceFolder);
catch exception
    runFailure = exception;
    result.execution_status = "failed_execution";
    result.execution_failure = struct( ...
        "identifier", string(exception.identifier), ...
        "message", string(exception.message));
end

writeStudyReport(reportPath, result);
fprintf("Range study report: %s\n", reportPath);
fprintf("Execution status: %s\n", result.execution_status);
if ~isempty(runFailure)
    rethrow(runFailure);
end
clear stateCleanup
end

function restoreStudyState(originalPath, originalRng)
%RESTORESTUDYSTATE Restore caller MATLAB path and default random stream.
path(originalPath);
rng(originalRng);
end

