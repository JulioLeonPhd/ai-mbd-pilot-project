function power = receivedPower(rangeM, constants, rcs)
%RECEIVEDPOWER Apply the approved monostatic radar equation for one RCS.

power = constants.radar_constant*rcs/(rangeM^4);
end

function envelope = generateTargetEnvelope(rangeM, phaseRad, pathIndex, constants)
%GENERATETARGETENVELOPE Evaluate the analytic delayed chirp on the path grid.

if pathIndex == 0
    time = constants.baseband_time_s;
else
    time = constants.adc_time_s;
end
delay = 2*rangeM/constants.speed_of_light;
relativeTime = time - delay;
active = relativeTime >= 0 & relativeTime < constants.pulse_width_s;
envelope = complex(zeros(size(time)));
chirpPhase = -constants.bandwidth_hz*relativeTime/2 + ...
    constants.bandwidth_hz*relativeTime.^2/(2*constants.pulse_width_s);
envelope(active) = exp(1i*(2*pi*chirpPhase(active) + phaseRad + ...
    2*pi*constants.doppler_hz*time(active)));
end

function signal = makePathSignal(envelope, pathIndex, constants)
%MAKEPATHSIGNAL Form ideal complex samples or the real passband ADC stimulus.

if pathIndex == 0
    signal = envelope;
else
    signal = real(envelope.*constants.adc_carrier);
end
end

function [baseband, valid, rangeOrigin, metadata, quantStats] = ...
        preparePathInput(pathIndex, inputSamples, design, constants, doQuantize)
%PREPAREPATHINPUT Apply the actual DDC when selected and make sample masks.

quantStats = repmat(makeQuantTemplate(), 1, size(inputSamples, 2));
if pathIndex == 0
    baseband = inputSamples;
    valid = true(size(inputSamples));
    valid(1:constants.blank_baseband_samples, :) = false;
    rangeOrigin = 0;
    metadata = struct();
else
    if doQuantize
        [inputSamples, quantStats] = quantizeCounts(inputSamples);
    end
    [baseband, metadata] = radardemo.ddc.processFrame(inputSamples, design);
    rangeOrigin = -metadata.groupDelayOutputSamples*constants.range_spacing_m;
    firstValid = ceil((ceil(constants.blank_guard_s*constants.adc_rate_hz) + ...
        metadata.startupInputSamples)/12);
    valid = false(size(baseband));
    if firstValid < size(baseband, 1)
        valid(firstValid + 1:end, :) = true;
    end
end
end

function reference = makeReference(constants)
%MAKEREFERENCE Create the fixed unit-amplitude ideal up-chirp reference.

time = (0:constants.reference_length - 1).' / constants.baseband_rate_hz;
phase = -constants.bandwidth_hz*time/2 + ...
    constants.bandwidth_hz*time.^2/(2*constants.pulse_width_s);
reference = exp(1i*2*pi*phase);
end

function [rangeSamples, valid, rangeCenters, fftLength] = compressRange( ...
        samples, inputValid, reference, constants, rangeOrigin)
%COMPRESSRANGE Compute normalized linear correlation on public nonnegative lags.

if nargin < 5
    rangeOrigin = 0;
end
sampleCount = size(samples, 1);
fftLength = 2^nextpow2(sampleCount + constants.reference_length - 1);
inputSpectrum = fft(samples, fftLength, 1);
referenceSpectrum = fft(reference, fftLength, 1);
fullCorrelation = ifft(inputSpectrum.*conj(referenceSpectrum), [], 1) / ...
    constants.reference_length;
rangeSamples = fullCorrelation(1:sampleCount, :);
valid = windowValidity(inputValid, constants.reference_length);
rangeSamples(~valid) = 0;
rangeCenters = rangeOrigin + (0:sampleCount - 1).' * constants.range_spacing_m;
end

function valid = windowValidity(inputValid, windowLength)
%WINDOWVALIDITY Require every in-range input mask sample for each lag.

sampleCount = size(inputValid, 1);
streamCount = size(inputValid, 2);
valid = false(sampleCount, streamCount);
if sampleCount < windowLength
    return
end
invalidPrefix = [zeros(1, streamCount); cumsum(double(~inputValid), 1)];
validRows = sampleCount - windowLength + 1;
invalidCounts = invalidPrefix(windowLength + 1:sampleCount + 1, :) - ...
    invalidPrefix(1:validRows, :);
valid(1:validRows, :) = invalidCounts == 0;
end

function [oracle, oracleValid] = directOracle(samples, inputValid, constants)
%DIRECTORACLE Independently sum every available public lag from the definition.

sampleCount = size(samples, 1);
streamCount = size(samples, 2);
windowLength = constants.reference_length;
oracle = complex(zeros(sampleCount, streamCount));
oracleValid = false(sampleCount, streamCount);
referenceTime = (0:windowLength - 1).' / constants.baseband_rate_hz;
referencePhase = -constants.bandwidth_hz*referenceTime/2 + ...
    constants.bandwidth_hz*referenceTime.^2/(2*constants.pulse_width_s);
conjugateReference = exp(-1i*2*pi*referencePhase);
for lag = 0:sampleCount - 1
    if lag + windowLength <= sampleCount
        for streamIndex = 1:streamCount
            windowMask = inputValid(lag + 1:lag + windowLength, streamIndex);
            if all(windowMask)
                windowSamples = samples(lag + 1:lag + windowLength, streamIndex);
                oracle(lag + 1, streamIndex) = ...
                    sum(windowSamples.*conjugateReference)/windowLength;
                oracleValid(lag + 1, streamIndex) = true;
            end
        end
    end
end
end

function [values, valid] = directAtLags(samples, inputValid, lags, constants)
%DIRECTATLAGS Independently sum only requested complete valid public lag windows.

streamCount = size(samples, 2);
windowLength = constants.reference_length;
values = complex(zeros(numel(lags), streamCount));
valid = false(numel(lags), streamCount);
referenceTime = (0:windowLength - 1).' / constants.baseband_rate_hz;
referencePhase = -constants.bandwidth_hz*referenceTime/2 + ...
    constants.bandwidth_hz*referenceTime.^2/(2*constants.pulse_width_s);
conjugateReference = exp(-1i*2*pi*referencePhase);
for lagIndex = 1:numel(lags)
    lag = lags(lagIndex);
    if lag >= 0 && lag + windowLength <= size(samples, 1)
        for streamIndex = 1:streamCount
            if all(inputValid(lag + 1:lag + windowLength, streamIndex))
                values(lagIndex, streamIndex) = sum( ...
                    samples(lag + 1:lag + windowLength, streamIndex).* ...
                    conjugateReference)/windowLength;
                valid(lagIndex, streamIndex) = true;
            end
        end
    end
end
end

function stats = compareCorrelations( ...
        fftValues, directValues, samples, valid, rangeOrigin, fftLength, constants)
%COMPARECORRELATIONS Summarize all-lag complex and phase-guard residuals.

stats = repmat(makeComparisonTemplate(), 1, size(samples, 2));
for streamIndex = 1:size(samples, 2)
    validLags = find(valid(:, streamIndex)) - 1;
    residual = fftValues(validLags + 1, streamIndex) - ...
        directValues(validLags + 1, streamIndex);
    bounds = correlationBounds(samples(:, streamIndex), validLags, fftLength, constants);
    magnitude = abs(residual);
    streamStats = makeComparisonTemplate();
    streamStats.stream_index_zero_based = streamIndex - 1;
    streamStats.valid_lag_count = numel(validLags);
    streamStats.f_zero_exact = all(samples(:, streamIndex) == 0) && all(residual == 0);
    if ~isempty(validLags)
        [maximumError, worstIndex] = max(magnitude);
        streamStats.max_absolute_complex_error = maximumError;
        streamStats.rms_complex_error = sqrt(mean(magnitude.^2));
        streamStats.worst_lag = validLags(worstIndex);
        streamStats.worst_range_m = rangeOrigin + ...
            streamStats.worst_lag*constants.range_spacing_m;
        streamStats.proposed_bound_at_worst_lag = bounds(worstIndex);
        ratios = zeros(size(magnitude));
        nonzeroBound = bounds > 0;
        ratios(nonzeroBound) = magnitude(nonzeroBound)./bounds(nonzeroBound);
        ratios(~nonzeroBound & magnitude > 0) = Inf;
        streamStats.max_error_to_proposed_bound_ratio = max(ratios);
        directAtValid = directValues(validLags + 1, streamIndex);
        fftAtValid = fftValues(validLags + 1, streamIndex);
        streamNorm = norm(samples(:, streamIndex), 2)/ ...
            sqrt(constants.reference_length);
        phaseGuard = abs(directAtValid) >= ...
            sqrt(constants.unit_roundoff)*streamNorm & abs(directAtValid) > bounds;
        phaseResidual = abs(angle(fftAtValid(phaseGuard).* ...
            conj(directAtValid(phaseGuard))));
        phaseBudget = atan2(bounds(phaseGuard), ...
            abs(directAtValid(phaseGuard)) - bounds(phaseGuard));
        streamStats.phase_guard_lag_count = sum(phaseGuard);
        streamStats.phase_guard_excluded_null_count = sum(~phaseGuard);
        if any(phaseGuard)
            [phaseMaximum, phaseWorst] = max(phaseResidual);
            guardLags = validLags(phaseGuard);
            streamStats.max_absolute_phase_residual_rad = phaseMaximum;
            streamStats.worst_phase_lag = guardLags(phaseWorst);
            streamStats.proposed_phase_budget_at_worst_lag_rad = ...
                phaseBudget(phaseWorst);
            streamStats.phase_budget_exceedance_count = ...
                sum(phaseResidual > phaseBudget);
        end
    end
    stats(streamIndex) = streamStats;
end
end

