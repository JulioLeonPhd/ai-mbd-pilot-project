if pathIndex == 1
    [quantizedCombined, combinedStats] = quantizeCounts(combinedInput);
    nonadditivity = quantizedCombined - known.isolated(1).quantized_input - ...
        known.isolated(2).quantized_input - noiseQuantized;
else
    quantizedCombined = combinedInput;
    combinedStats = repmat(makeQuantTemplate(), 1, 4);
    noiseQuantStats = repmat(makeQuantTemplate(), 1, 4);
    nonadditivity = zeros(size(combinedInput));
end
[baseband, inputValid, rangeOrigin] = preparePathInput( ...
    pathIndex, quantizedCombined, design, constants, false);
[rangeSamples, valid, ~] = compressRange( ...
    baseband, inputValid, constants.reference, constants, rangeOrigin);
assert(isequal(valid, known.valid), ...
    "Known-signal and noisy records must share the same validity mask.");
if pathIndex == 1
    unquantizedResponse = known.range_samples + noiseRange;
    responseDelta = rangeSamples - unquantizedResponse;
else
    responseDelta = zeros(size(rangeSamples));
end
responseDelta(~valid) = 0;
preflightAmplitude = known.isolated(1).amplitude_counts + ...
    known.isolated(2).amplitude_counts;

for streamIndex = 1:4
    stream = makeStreamTemplate();
    stream.stream_index_zero_based = streamIndex - 1;
    stream.evaluation_status = "evaluated";
    pair = evaluatePeakPair( ...
        abs(rangeSamples(:, streamIndex)), valid(:, streamIndex), known.coordinates, ...
        geometry.near_range_m, geometry.far_range_m, constants.range_spacing_m);
    stream.near_peak_found = pair.near_found;
    stream.far_peak_found = pair.far_found;
    stream.peaks_distinct = pair.peaks_distinct;
    stream.valley_available = pair.valley_available;
    stream.valley_status = pair.valley_status;
    stream.valley_lag = pair.valley_index - 1;
    stream.valley_pass = pair.valley_pass;
    stream.valley_depth_status = pair.valley_depth_status;
    stream.valley_to_weaker_peak_power_ratio = pair.valley_ratio;
    stream.valley_power_counts_squared = pair.valley_power;
    stream.valley_depth_db = pair.valley_depth_db;
    stream.near_isolated_fwhm_m = known.isolated(1).isolated_fwhm_m;
    stream.near_isolated_fwhm_left_crossing_m = ...
        known.isolated(1).isolated_fwhm_left_crossing_m;
    stream.near_isolated_fwhm_right_crossing_m = ...
        known.isolated(1).isolated_fwhm_right_crossing_m;
    stream.near_isolated_fwhm_status = known.isolated(1).isolated_fwhm_status;
    stream.far_isolated_fwhm_m = known.isolated(2).isolated_fwhm_m;
    stream.far_isolated_fwhm_left_crossing_m = ...
        known.isolated(2).isolated_fwhm_left_crossing_m;
    stream.far_isolated_fwhm_right_crossing_m = ...
        known.isolated(2).isolated_fwhm_right_crossing_m;
    stream.far_isolated_fwhm_status = known.isolated(2).isolated_fwhm_status;
    stream.isolated_fwhm_reused_from_known_geometry = true;
    if pair.near_found
        stream.near_peak_lag = pair.near_index - 1;
        stream.near_peak_range_m = known.coordinates(pair.near_index);
        stream.near_peak_power_counts_squared = abs( ...
            rangeSamples(pair.near_index, streamIndex))^2;
        stream.near_combined_noisy_localization_error_m = ...
            stream.near_peak_range_m - geometry.near_range_m;
    end
    if pair.far_found
        stream.far_peak_lag = pair.far_index - 1;
        stream.far_peak_range_m = known.coordinates(pair.far_index);
        stream.far_peak_power_counts_squared = abs( ...
            rangeSamples(pair.far_index, streamIndex))^2;
        stream.far_combined_noisy_localization_error_m = ...
            stream.far_peak_range_m - geometry.far_range_m;
    end
    if pair.near_found && pair.far_found
        stream.measured_peak_spacing_m = ...
            stream.far_peak_range_m - stream.near_peak_range_m;
    end
    stream.near_physical_receiver_input_snr_db = ...
        known.isolated(1).receiver_input_snr_db;
    stream.far_physical_receiver_input_snr_db = ...
        known.isolated(2).receiver_input_snr_db;
    stream.range_input_noise_power_counts_squared = ...
        rangeInputNoiseEvidence.range_input_noise_power_counts_squared(streamIndex);
    stream.range_input_noise_interior_range_m = ...
        rangeInputNoiseEvidence.range_input_noise_interior_range_m;
    stream.range_input_noise_interior_range_convention = ...
        rangeInputNoiseEvidence.range_input_noise_interior_range_convention;
    stream.range_input_noise_reference_record_index = ...
        rangeInputNoiseEvidence.seed_record_index;
    stream.range_input_noise_interior_indices_zero_based_inclusive = ...
        rangeInputNoiseEvidence.range_input_noise_interior_indices_zero_based_inclusive;
    stream.range_input_noise_interior_sample_count = ...
        rangeInputNoiseEvidence.range_input_noise_interior_sample_count;
    stream.near_range_input_signal_power_counts_squared = ...
        known.isolated(1).range_input_signal_power_counts_squared;
    stream.far_range_input_signal_power_counts_squared = ...
        known.isolated(2).range_input_signal_power_counts_squared;
    stream.near_range_input_snr_db = 10*log10( ...
        stream.near_range_input_signal_power_counts_squared / ...
        stream.range_input_noise_power_counts_squared);
    stream.far_range_input_snr_db = 10*log10( ...
        stream.far_range_input_signal_power_counts_squared / ...
        stream.range_input_noise_power_counts_squared);
    stream.near_received_power_w = known.isolated(1).received_power_w;
    stream.far_received_power_w = known.isolated(2).received_power_w;
    stream.output_noise_power_counts_squared = noisePower(streamIndex);
    if pair.far_found
        farIndex = find(known.isolated(2).candidate_lags == pair.far_index - 1, 1);
        if ~isempty(farIndex) && known.isolated(2).candidate_valid(farIndex)
            isolatedFar = known.isolated(2).candidate_responses(farIndex);
            stream.far_isolated_power_at_selected_lag_counts_squared = abs(isolatedFar)^2;
            isolatedPowers = abs(known.isolated(2).candidate_responses( ...
                known.isolated(2).candidate_valid)).^2;
            if ~isempty(isolatedPowers)
                stream.far_isolated_peak_power_counts_squared = max(isolatedPowers);
                stream.isolated_peak_snr_db = 10*log10( ...
                    stream.far_isolated_peak_power_counts_squared/noisePower(streamIndex));
            end
            stream.post_compression_snr_at_selected_lag_db = 10*log10( ...
                stream.far_isolated_power_at_selected_lag_counts_squared/ ...
                noisePower(streamIndex));
            stream.snr_pass = stream.post_compression_snr_at_selected_lag_db >= 30;
            unitValue = known.isolated(2).unit_candidate_response(farIndex);
            stream.far_isolated_quantization_delta_at_selected_lag_counts = ...
                abs(isolatedFar - known.isolated(2).amplitude_counts*unitValue);
        else
            stream.failure_reasons(end + 1, 1) = ...
                "far_isolated_response_unavailable_at_selected_lag";
        end
    end
    if pathIndex == 1
        stream.combined_quantization_status = "quantized_signal_plus_noise_together";
        stream.combined_prequantizer_excursion_count = ...
            combinedStats(streamIndex).prequantizer_excursion_count;
        stream.combined_rounded_out_of_range_count = ...
            combinedStats(streamIndex).rounded_out_of_range_count;
        stream.separation_noise_rounded_out_of_range_count = ...
            noiseQuantStats(streamIndex).rounded_out_of_range_count;
        stream.near_isolated_rounded_out_of_range_count = ...
            known.isolated(1).quantizer_statistics.rounded_out_of_range_count;
        stream.far_isolated_rounded_out_of_range_count = ...
            known.isolated(2).quantizer_statistics.rounded_out_of_range_count;
        stream.actual_max_absolute_adc_counts = ...
            combinedStats(streamIndex).raw_peak_absolute_counts;
        stream.actual_adc_headroom_counts = ...
            combinedStats(streamIndex).actual_headroom_to_code_limits_counts;
        stream.preflight_max_absolute_adc_counts = preflightAmplitude + ...
            max(abs(noiseInput(:, streamIndex)));
        stream.preflight_adc_headroom_counts = ...
            32767 - stream.preflight_max_absolute_adc_counts;
        validDelta = responseDelta(valid(:, streamIndex), streamIndex);
        stream.quantized_combined_response_rms_delta_counts = ...
            sqrt(mean(abs(validDelta).^2));
        stream.quantized_combined_response_max_delta_counts = max(abs(validDelta));
        stream.quantizer_nonadditivity_rms_counts = ...
            sqrt(mean(nonadditivity(:, streamIndex).^2));
        stream.quantizer_nonadditivity_max_absolute_counts = ...
            max(abs(nonadditivity(:, streamIndex)));
        clipCounts = [stream.combined_rounded_out_of_range_count, ...
            stream.separation_noise_rounded_out_of_range_count, ...
            stream.near_isolated_rounded_out_of_range_count, ...
            stream.far_isolated_rounded_out_of_range_count];
        if any(clipCounts > 0)
            stream.adc_clip_pass = false;
            stream.failure_reasons(end + 1, 1) = "adc_clipping_or_saturation";
        end
    end
    if ~pair.near_found
        stream.failure_reasons(end + 1, 1) = "near_peak_not_found_within_one_bin";
    end
    if ~pair.far_found
        stream.failure_reasons(end + 1, 1) = "far_peak_not_found_within_one_bin";
    end
    if pair.near_found && pair.far_found && ~pair.peaks_distinct
        stream.failure_reasons(end + 1, 1) = "two_targets_selected_the_same_peak";
    end
    if ~pair.valley_available
        stream.failure_reasons(end + 1, 1) = "valid_intervening_valley_unavailable";
    elseif ~pair.valley_pass
        stream.failure_reasons(end + 1, 1) = "valley_not_three_db_below_weaker_peak";
    end
    if ~stream.snr_pass
        stream.failure_reasons(end + 1, 1) = "post_compression_snr_below_30_db_or_unavailable";
    end
    stream.criteria_pass = pair.near_found && pair.far_found && ...
        pair.peaks_distinct && pair.valley_available && pair.valley_pass && ...
        stream.snr_pass && stream.adc_clip_pass;
    caseResult.stream_results(streamIndex) = stream;
end
caseResult.evaluation_status = "evaluated";
caseResult.criteria_pass = all([caseResult.stream_results.criteria_pass]);
for streamIndex = 1:4
    caseResult.failure_reasons = [caseResult.failure_reasons; ...
        caseResult.stream_results(streamIndex).failure_reasons(:)];
end
caseResult.failure_reasons = unique(caseResult.failure_reasons, "stable");
end

function summary = summarizeCriteria(cases, noiseOnly, rcsEvidence, completedCount)
%SUMMARIZECRITERIA Count fixed physical criteria without approving tolerances.

summary = struct( ...
    "physical_criteria_status", "failed_or_incomplete", ...
    "physical_criteria_pass", false, ...
    "path_case_seed_records", numel(cases), ...
    "stream_records", 4*numel(cases), ...
    "completed_stream_evaluations", completedCount, ...
    "near_peak_pass_count", 0, ...
    "far_peak_pass_count", 0, ...
    "distinct_peak_pass_count", 0, ...
    "valid_valley_pass_count", 0, ...
    "three_db_valley_pass_count", 0, ...
    "thirty_db_snr_pass_count", 0, ...
    "adc_clip_pass_count", 0, ...
    "failed_case_count", 0, ...
    "noise_only_adc_clipping_count", 0, ...
    "common_rcs_status", rcsEvidence.status, ...
    "tolerance_approval_status", "pending_julio_review");
for caseIndex = 1:numel(cases)
    if ~cases(caseIndex).criteria_pass
        summary.failed_case_count = summary.failed_case_count + 1;
    end
    for streamIndex = 1:4
        item = cases(caseIndex).stream_results(streamIndex);
        summary.near_peak_pass_count = summary.near_peak_pass_count + item.near_peak_found;
        summary.far_peak_pass_count = summary.far_peak_pass_count + item.far_peak_found;
        summary.distinct_peak_pass_count = summary.distinct_peak_pass_count + item.peaks_distinct;
        summary.valid_valley_pass_count = summary.valid_valley_pass_count + item.valley_available;
        summary.three_db_valley_pass_count = summary.three_db_valley_pass_count + item.valley_pass;
        summary.thirty_db_snr_pass_count = summary.thirty_db_snr_pass_count + item.snr_pass;
        summary.adc_clip_pass_count = summary.adc_clip_pass_count + item.adc_clip_pass;
    end
end
for pathIndex = 1:numel(noiseOnly)
    for streamIndex = 1:4
        if noiseOnly(pathIndex).quantizer_statistics(streamIndex).rounded_out_of_range_count > 0
            summary.noise_only_adc_clipping_count = ...
                summary.noise_only_adc_clipping_count + 1;
        end
    end
end
summary.physical_criteria_pass = all([cases.criteria_pass]) && ...
    summary.noise_only_adc_clipping_count == 0 && ...
    strcmp(rcsEvidence.status, "derived") && completedCount == 384;
if summary.physical_criteria_pass
    summary.physical_criteria_status = "all_fixed_physical_criteria_passed";
else
    summary.physical_criteria_status = "one_or_more_fixed_criteria_failed_or_unavailable";
end
end

