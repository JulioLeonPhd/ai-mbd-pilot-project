function report = checkCorrelationContract(constants)
%CHECKCORRELATIONCONTRACT Exercise aligned complex recovery and all-lag agreement.

sampleCount = 1000;
windowLength = constants.reference_length;
reference = constants.reference;
delays = [0, 37, 243, sampleCount - windowLength];
amplitudes = [1.2 - 0.8i, -0.6 + 1.7i, 2.1 + 0.3i, -1.3 - 1.1i];
samples = complex(zeros(sampleCount, 4));
for streamIndex = 1:4
    firstSample = delays(streamIndex) + 1;
    samples(firstSample:firstSample + windowLength - 1, streamIndex) = ...
        amplitudes(streamIndex)*reference;
end
inputValid = true(sampleCount, 4);
[output, valid, coordinates, fftLength] = compressRange( ...
    samples, inputValid, reference, constants, -31*constants.range_spacing_m);
[oracle, oracleValid] = directOracle(samples, inputValid, constants);
assert(isequal(size(output), [sampleCount, 4]), ...
    "The public output must retain exactly N rows and four streams.");
assert(isequal(valid, oracleValid), "Aligned known-signal masks must agree.");
assert(all(valid(1:sampleCount - windowLength + 1, :), "all"), ...
    "All complete aligned windows must be valid.");
assert(~any(valid(sampleCount - windowLength + 2:end, :), "all"), ...
    "The last 499 public output rows must be invalid.");
assert(all(output(~valid) == 0), "Invalid public outputs must be exact complex zero.");
assert(coordinates(1) == -31*constants.range_spacing_m, ...
    "Negative range origins must be retained without another delay correction.");
assert(coordinates(end) == -31*constants.range_spacing_m + ...
    (sampleCount - 1)*constants.range_spacing_m, ...
    "Coordinates must retain the complete fixed public lag grid.");
recovered = complex(zeros(1, 4));
exactPeakLags = zeros(1, 4);
allValidLagComparisonCounts = zeros(1, 4);
fftKnownRecoveryPassed = false(1, 4);
