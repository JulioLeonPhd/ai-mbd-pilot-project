function caseResult = makeFailedCase( ...
        pathIndex, geometry, geometryIndex, seedIndex, exception)
%MAKEFAILEDCASE Preserve an unexpected case failure across all streams.

caseResult = makeUnavailableCase(pathIndex, geometry, geometryIndex, seedIndex, ...
    "Case evaluation failed: " + string(exception.message));
caseResult.evaluation_status = "failed_evaluation";
for streamIndex = 1:4
    caseResult.stream_results(streamIndex).evaluation_status = "failed_evaluation";
    caseResult.stream_results(streamIndex).failure_reasons = ...
        "case_exception:" + string(exception.identifier);
end
end


function writeStudyReport(reportPath, result)
%WRITESTUDYREPORT Write complete JSON with cleanup on every file-I/O path.

jsonText = jsonencode(result, "PrettyPrint", true);
[fileId, message] = fopen(reportPath, "w");
if fileId < 0
    error("rangeStudy:ReportOpenFailed", ...
        "Unable to open report file %s: %s", reportPath, message);
end
fileCleanup = onCleanup(@() closeIfOpen(fileId));
written = fwrite(fileId, jsonText, "char");
if written ~= numel(jsonText)
    error("rangeStudy:ReportWriteFailed", ...
        "Only %d of %d report characters were written.", written, numel(jsonText));
end
closeStatus = fclose(fileId);
if closeStatus ~= 0
    error("rangeStudy:ReportCloseFailed", ...
        "Unable to close report file %s cleanly.", reportPath);
end
clear fileCleanup
end

function closeIfOpen(fileId)
%CLOSEIFOPEN Close a report file if an earlier failure left it open.

if any(openedFiles() == fileId)
    fclose(fileId);
end
end

function hashValue = sha256File(filePath)
%SHA256FILE Return a lowercase SHA-256 digest for exact file bytes.

[fileId, message] = fopen(filePath, "rb");
if fileId < 0
    error("rangeStudy:SourceOpenFailed", ...
        "Unable to open source file %s: %s", filePath, message);
end
fileCleanup = onCleanup(@() closeIfOpen(fileId));
fileBytes = fread(fileId, Inf, "*uint8");
fclose(fileId);
clear fileCleanup
messageDigest = java.security.MessageDigest.getInstance("SHA-256");
messageDigest.update(typecast(fileBytes(:), "int8"));
digestBytes = typecast(messageDigest.digest(), "uint8");
hashValue = lower(string(reshape(dec2hex(digestBytes, 2).', 1, [])));
end

