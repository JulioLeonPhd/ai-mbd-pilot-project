    assert(fftKnownRecoveryPassed(streamIndex), ...
        "The aligned FFT must recover the known complex amplitude within the proposed bound.");
    [~, peakOffset] = max(abs(output(validIndices, streamIndex)).^2);
    exactPeakLags(streamIndex) = validLags(peakOffset);
    assert(exactPeakLags(streamIndex) == lag, ...
        "Each aligned stream must peak at its exact injected lag.");
end
assert(all(allValidLagComparisonCounts == sum(valid, 1)), ...
    "Reported oracle comparison counts must equal all valid public lags.");
assert(all(fftKnownRecoveryPassed), ...
    "Reported direct FFT-to-known recovery count must include every stream.");
assert(numel(unique(delays)) == 4, "The aligned-delay self-check needs four distinct lags.");
zeroOutput = compressRange(zeros(sampleCount, 4), inputValid, reference, constants);
assert(all(zeroOutput(:) == 0), "A zero signal must produce exact zero output.");
alignedGain = abs(recovered)./abs(amplitudes);
alignedPhase = angle(recovered.*conj(amplitudes));
report = struct( ...
    "status", "passed", ...
    "sample_count", sampleCount, ...
    "tested_delays", delays, ...
    "tested_complex_amplitudes", struct("real", real(amplitudes), "imag", imag(amplitudes)), ...
    "recovered_complex_amplitudes", struct("real", real(recovered), "imag", imag(recovered)), ...
    "aligned_gain_magnitude_ratio", alignedGain, ...
    "aligned_phase_residual_rad", alignedPhase, ...
    "aligned_gain_phase_recovered_with_proposed_bound", all(fftKnownRecoveryPassed), ...
    "direct_fft_to_known_recovery_count", sum(fftKnownRecoveryPassed), ...
    "exact_peak_lags_zero_based", exactPeakLags, ...
    "public_output_rows", size(output, 1), ...
    "all_valid_lags_compared_to_direct_oracle", allValidLagComparisonCounts, ...
