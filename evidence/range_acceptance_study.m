function bounds = correlationBounds(samples, lags, fftLength, constants)
%CORRELATIONBOUNDS Evaluate the predeclared engineering error proposal.

unitRoundoff = constants.unit_roundoff;
termCount = 8*constants.reference_length;
gamma = termCount*unitRoundoff/(1 - termCount*unitRoundoff);
streamNorm = norm(samples, 2)/sqrt(constants.reference_length);
prefixMagnitude = [0; cumsum(abs(samples))];
firstPrefix = lags + 1;
lastPrefix = lags + constants.reference_length + 1;
qValues = (prefixMagnitude(lastPrefix) - prefixMagnitude(firstPrefix))/ ...
    constants.reference_length;
bounds = gamma*qValues + 128*unitRoundoff*(log2(fftLength) + 1)*streamNorm;
end

