classdef TestDdcWalkthrough < matlab.unittest.TestCase
%TESTDDCWALKTHROUGH Check the one-PRI lesson and preserved full-scan example.

methods (TestClassSetup)
    function addSourcePath(testCase)
        repositoryRoot = fileparts(fileparts(fileparts(mfilename("fullpath"))));
        testCase.applyFixture(matlab.unittest.fixtures.PathFixture( ...
            fullfile(repositoryRoot, "src")));
    end
end

methods (Test)
    function testAcademicPriAndFullScanCheck(testCase)
        repositoryRoot = fileparts(fileparts(fileparts(mfilename("fullpath"))));
        existingFigures = findall(groot, "Type", "figure");
        testCase.addTeardown(@() closeNewFigures(existingFigures));
        fullScanOutputDirectory = tempname;
        testCase.addTeardown(@() removeTemporaryDirectory( ...
            fullScanOutputDirectory));

        walkthrough = runWalkthroughForTest(fullfile( ...
            repositoryRoot, "examples", "runDdcWalkthrough.m"));

        testCase.verifyEqual(walkthrough.startTick, 0);
        testCase.verifyEqual(walkthrough.sampleCount, 88236);
        testCase.verifyEqual(walkthrough.chirpCenterFrequencyHz, 50e6);
        testCase.verifyEqual(walkthrough.chirpStartFrequencyHz, 47.5e6);
        testCase.verifyEqual(walkthrough.chirpEndFrequencyHz, 52.5e6);
        testCase.verifyClass(walkthrough.adcPriSamples, "int16");
        testCase.verifySize(walkthrough.adcPriSamples, [88236, 1]);
        testCase.verifyEqual(walkthrough.adcPriSamples(1), int16(21500));
        testCase.verifySize(walkthrough.output, [7353, 1]);
        testCase.verifyFalse(isreal(walkthrough.output));
        testCase.verifyEqual( ...
            [walkthrough.metadata.groupDelayInputSamples, ...
            walkthrough.metadata.groupDelayOutputSamples, ...
            walkthrough.metadata.startupInputSamples, ...
            walkthrough.metadata.startupOutputSamples], ...
            [372, 31, 744, 62]);

        repeatedOutput = radardemo.ddc.processFrame( ...
            walkthrough.adcPriDouble, walkthrough.design);
        testCase.verifyEqual(repeatedOutput, walkthrough.output);

        instantaneousFrequencyHz = angle(walkthrough.output(2:end) .* ...
            conj(walkthrough.output(1:end - 1))) * ...
            walkthrough.design.outputRateHz / (2 * pi);
        frequencyIntervalIndex = (0:numel(instantaneousFrequencyHz) - 1).';
        expectedFrequencyHz = walkthrough.chirpStartFrequencyHz - ...
            walkthrough.design.mixerFrequencyHz + ...
            walkthrough.chirpRateHzPerSecond * ...
            (12 * frequencyIntervalIndex + 6 - ...
            walkthrough.metadata.groupDelayInputSamples) / ...
            walkthrough.design.adcRateHz;
        earlyWindow = frequencyIntervalIndex >= 500 & ...
            frequencyIntervalIndex <= 650;
        lateWindow = frequencyIntervalIndex >= 6500 & ...
            frequencyIntervalIndex <= 6650;
        earlyFrequencyErrorHz = median(instantaneousFrequencyHz(earlyWindow)) - ...
            median(expectedFrequencyHz(earlyWindow));
        lateFrequencyErrorHz = median(instantaneousFrequencyHz(lateWindow)) - ...
            median(expectedFrequencyHz(lateWindow));
        testCase.verifyLessThanOrEqual(abs(earlyFrequencyErrorHz), 2e3);
        testCase.verifyLessThanOrEqual(abs(lateFrequencyErrorHz), 2e3);
        testCase.verifyGreaterThan( ...
            median(instantaneousFrequencyHz(lateWindow)), ...
            median(instantaneousFrequencyHz(earlyWindow)));

        fullScan = runDdcScanCheck(fullScanOutputDirectory);
        testCase.verifyEqual( ...
            [fullScan.physicalPriCallCount, fullScan.skippedTransitionCount, ...
            fullScan.totalScanTicks, fullScan.outputSampleCount], ...
            [147, 4, 10553388, 843825]);
        expectedFigureNames = [ ...
            "ddc-stage1-alias-response.png", ...
            "ddc-stage2-alias-response.png", ...
            "ddc-cascade-alias-response.png", ...
            "ddc-passband-zoom.png"];
        testCase.verifyTrue(all(isfile(fullfile( ...
            fullScanOutputDirectory, expectedFigureNames))));
    end
end
end

function walkthrough = runWalkthroughForTest(scriptPath)
run(scriptPath);
walkthrough = struct( ...
    "startTick", startTick, ...
    "sampleCount", sampleCount, ...
    "adcPriSamples", adcPriSamples, ...
    "adcPriDouble", adcPriDouble, ...
    "design", design, ...
    "output", output, ...
    "metadata", metadata, ...
    "chirpStartFrequencyHz", chirpStartFrequencyHz, ...
    "chirpEndFrequencyHz", chirpEndFrequencyHz, ...
    "chirpCenterFrequencyHz", chirpCenterFrequencyHz, ...
    "chirpRateHzPerSecond", chirpRateHzPerSecond);
end

function closeNewFigures(existingFigures)
newFigures = setdiff(findall(groot, "Type", "figure"), existingFigures);
close(newFigures);
end

function removeTemporaryDirectory(folder)
if isfolder(folder)
    rmdir(folder, "s");
end
end
