function record = makeGeneratedRecord(artifact, profile, options)
sourceRevision = string(options.GeneratorRevision);
if isempty(regexp(char(sourceRevision), "^[0-9A-Fa-f]{40}$", "once"))
    sourceRevision = "working-tree";
end
record = struct("artifact", artifact, "profile", profile, ...
    "evidenceScope", char(options.FixtureScope), ...
    "generatorVersion", char(options.GeneratorVersion), ...
    "generatorRevision", char(options.GeneratorRevision), ...
    "createdUtc", char(options.CreatedUtc), "generatorSeed", options.Seeds.ddc, ...
    "sourceRevision", char(sourceRevision), "sha256", "");
end
