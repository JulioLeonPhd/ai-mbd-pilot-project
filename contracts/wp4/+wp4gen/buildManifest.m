function output = makeRow(identifier, artifact, domain, method, expected, code, path, clause, mutation)
if nargin < 9
    mutation = struct([]);
end
output = struct("id", identifier, "artifact", artifact, "domain", domain, ...
    "testMethod", method, "expected", expected, "expectedCode", code, ...
    "expectedPath", path, "clause", "docs/contracts/radar-v1-data-contracts.md#" + clause, ...
    "productionEntryPoint", productionEntryPoint(domain), "provenanceSeed", ...
    seedForDomain(domain), "mutation", mutation);
end

function seed = seedForDomain(domain)
switch domain
    case {"schedule", "timing"}
        seed = 401011;
    case {"ddc", "ddc-streaming", "ddc-zero", "ddc-response-pri", "ddc-pri"}
        seed = 401021;
    case "beam"
        seed = 401031;
    case {"fusion-pass", "fusion-fail", "fusion-invalid", "fusion-zero"}
        seed = 401041;
    case "clustering"
        seed = 401051;
    case "migration"
        seed = 401061;
    otherwise
        seed = 401002;
end
end

function entryPoint = productionEntryPoint(domain)
switch domain
    case "schedule"
        entryPoint = "radardemo.schedule.createReceiveSchedule";
    case "timing"
        entryPoint = "radardemo.timing.evaluateReceiveTiming";
    case "ddc-streaming"
        entryPoint = "radardemo.ddc.processFrame";
    case "ddc-pri"
        entryPoint = "radardemo.ddc.processFrame";
    case "ddc-response-pri"
        entryPoint = "radardemo.ddc.measureResponse";
    case {"ddc", "ddc-zero"}
        entryPoint = "radardemo.ddc.createDesign";
    case "beam"
        entryPoint = "radardemo.beamforming.formCommandedLook";
    case {"fusion-pass", "fusion-fail", "fusion-invalid", "fusion-zero"}
        entryPoint = "radardemo.fusion.fuseFivePrf";
    case "clustering"
        entryPoint = "radardemo.clustering.clusterHypotheses";
    case "migration"
        entryPoint = "adaptWp4Draft1";
    otherwise
        entryPoint = "checkWp4Fixtures";
end
end

function mutation = replaceMutation(path, value)
mutation = struct("operation", "replace", "path", path, "valueKind", "", "value", value);
end

function mutation = replaceMutationKind(path, kind, value)
mutation = struct("operation", "replace", "path", path, "valueKind", kind, "value", value);
end

function mutation = combinedScheduleMutation()
mutation = [replaceMutation("schemaVersion", "2.0.0"), replaceMutation("priSampleCounts[1]", 0)];
end

function mutation = combinedDdcMutation()
mutation = [replaceMutation("stopbandStartHz", 6251000), replaceMutationKind("stage2Numerator", "kaiser", 2)];
end

function mutation = combinedFusionMutation()
mutation = [replaceMutation("passMask", true), replaceMutation("voteThreshold", 2)];
end

function mutation = fusionSupportSubsetMutation()
mutation = [replaceMutation("validityMask", [true, true, true, true, false]), ...
    replaceMutation("supportMask", true(1, 5))];
end

function mutation = combinedClusterMutation()
